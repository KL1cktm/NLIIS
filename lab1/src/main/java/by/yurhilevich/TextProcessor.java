package by.yurhilevich;

import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

public class TextProcessor {

    private static final Set<String> STOP_WORDS = new HashSet<>(Arrays.asList(
            "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как", "а", "то",
            "все", "она", "так", "его", "но", "да", "ты", "к", "у", "же", "вы", "за",
            "бы", "по", "только", "ее", "мне", "было", "вот", "от", "меня", "еще",
            "нет", "о", "из", "ему", "теперь", "когда", "даже", "ну", "вдруг", "ли",
            "если", "уже", "или", "ни", "быть", "был", "него", "до", "вас", "нибудь",
            "опять", "уж", "вам", "ведь", "там", "потом", "себя", "ничего", "ей",
            "может", "они", "тут", "где", "есть", "надо", "ней", "для", "мы", "тебя",
            "их", "чем", "была", "сам", "чтоб", "без", "будто", "чего", "раз", "тоже",
            "себе", "под", "будет", "ж", "тогда", "кто", "этот", "того", "потому",
            "этого", "какой", "совсем", "ним", "здесь", "этом", "один", "почти",
            "мой", "тем", "чтобы", "нее", "сейчас", "были", "куда", "зачем", "всех",
            "никогда", "можно", "при", "наконец", "два", "об", "другой", "хоть",
            "после", "над", "больше", "тот", "через", "эти", "нас", "про", "всего",
            "них", "какая", "много", "разве", "три", "эту", "моя", "впрочем",

            "свою", "кажется", "кроме", "нельзя", "будто", "часто", "всегда"
    ));

    public static String preprocess(String text) {
        if (text == null || text.isEmpty()) {
            return "";
        }
        text = text.toLowerCase();
        text = text.replaceAll("[^а-яё\\s]", "");
        String[] words = text.split("\\s+");
        StringBuilder result = new StringBuilder();
        for (String word : words) {
            if (!STOP_WORDS.contains(word.trim())) {
                result.append(word).append(" ");
            }
        }
        // Лемматизация здесь не добавлена, т.к. RussianAnalyzer в Lucene делает это сам
        return result.toString().trim();
    }
}
